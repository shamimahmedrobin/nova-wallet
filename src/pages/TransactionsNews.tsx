import { useMemo, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { Link, useParams } from 'react-router-dom'
import { Bell, FileText, Search, X , CheckCheck, ChevronRight } from 'lucide-react'
import { useApp } from '../lib/store'
import { Badge, Btn, Card, Empty, Modal, NewsLogo, statusTone } from '../components/ui'
import { fmtDate, fmtDateTime } from '../lib/utils'
import { PageHead } from './Services'
import type { Tx } from '../lib/types'

const CATS = ['all', 'add_money', 'cash_out', 'send', 'receive', 'referral', 'loan_disbursement', 'loan_repayment', 'crypto_buy', 'crypto_sell', 'adjustment', 'direct_withdraw', 'earn', 'swap']
const catLabel = (c: string) => c.replace(/_/g, ' ')

export function Transactions() {
  const { user, db, t, fmtMoney } = useApp()
  const [q, setQ] = useState(''); const [cat, setCat] = useState('all'); const [status, setStatus] = useState('all')
  const [from, setFrom] = useState(''); const [to, setTo] = useState(''); const [sel, setSel] = useState<Tx | null>(null)
  const mine = useMemo(() => db.txs.filter(t => t.userId === user?.id)
    .filter(t => cat === 'all' || t.category === cat)
    .filter(t => status === 'all' || t.status === status)
    .filter(t => !q || t.id.toLowerCase().includes(q.toLowerCase()) || t.title.toLowerCase().includes(q.toLowerCase()))
    .filter(t => !from || t.createdAt >= from)
    .filter(t => !to || t.createdAt <= to + 'T23:59'), [db.txs, user, q, cat, status, from, to])
  const printReceipt = (t: Tx) => {
    const w = window.open('', '_blank'); if (!w) return
    w.document.write(`<html><head><title>Receipt ${t.id}</title><style>body{font-family:sans-serif;padding:40px;color:#111}h1{color:#6d28d9}table{width:100%;border-collapse:collapse}td{padding:8px;border-bottom:1px solid #eee}</style></head><body><h1>NovaWallet — Transaction Receipt</h1><table>
      <tr><td>Transaction ID</td><td><b>${t.id}</b></td></tr><tr><td>Title</td><td>${t.title}</td></tr>
      <tr><td>Category</td><td>${catLabel(t.category)}</td></tr><tr><td>Amount</td><td><b>৳${t.amount.toLocaleString()}</b></td></tr>
      <tr><td>Fee</td><td>৳${t.fee}</td></tr><tr><td>Status</td><td>${t.status}</td></tr>
      <tr><td>Date</td><td>${new Date(t.createdAt).toLocaleString()}</td></tr>${t.note ? `<tr><td>Note</td><td>${t.note}</td></tr>` : ''}</table>
      <p style="color:#888;font-size:12px;margin-top:24px">This receipt was generated by NovaWallet. Save as PDF from the print dialog.</p><script>window.print()</script></body></html>`)
    w.document.close()
  }
  return (
    <div>
      <PageHead title={t('tx_title')} sub={t('tx_sub')} />
      <div className="relative mb-3">
        <Search size={17} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
        <input value={q} onChange={e => setQ(e.target.value)} placeholder={t('search_tx')} className="w-full rounded-2xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800/70 pl-10 pr-4 py-3 text-[15px] outline-none focus:ring-2 focus:ring-violet-500" />
      </div>
      <div className="flex gap-2 overflow-x-auto no-scrollbar mb-3 -mx-4 px-4">
        {CATS.map(c => <button key={c} onClick={() => setCat(c)} className={`shrink-0 px-3.5 py-2 rounded-full text-xs font-bold capitalize ${cat === c ? 'bg-violet-600 text-white' : 'bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-slate-500'}`}>{catLabel(c)}</button>)}
      </div>
      <Card className="p-4 mb-4 space-y-3">
        <label className="block">
          <span className="block text-[11px] font-bold uppercase tracking-wide text-slate-400 mb-1.5">{t('status')}</span>
          <select value={status} onChange={e => setStatus(e.target.value)} className="w-full min-w-0 rounded-xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 px-3 py-2.5 text-sm outline-none focus:ring-2 focus:ring-violet-500"><option value="all">{t('all_status')}</option>{['pending', 'processing', 'completed', 'approved', 'rejected'].map(s2 => <option key={s2}>{s2}</option>)}</select>
        </label>
        <div className="grid grid-cols-2 gap-3">
          <label className="block min-w-0">
            <span className="block text-[11px] font-bold uppercase tracking-wide text-slate-400 mb-1.5">{t('from')}</span>
            <input type="date" value={from} onChange={e => setFrom(e.target.value)} className="w-full min-w-0 rounded-xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 px-3 py-2.5 text-sm outline-none focus:ring-2 focus:ring-violet-500" />
          </label>
          <label className="block min-w-0">
            <span className="block text-[11px] font-bold uppercase tracking-wide text-slate-400 mb-1.5">{t('to')}</span>
            <input type="date" value={to} onChange={e => setTo(e.target.value)} className="w-full min-w-0 rounded-xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 px-3 py-2.5 text-sm outline-none focus:ring-2 focus:ring-violet-500" />
          </label>
        </div>
        {(cat !== 'all' || status !== 'all' || from || to || q) && (
          <button onClick={() => { setCat('all'); setStatus('all'); setFrom(''); setTo(''); setQ('') }} className="inline-flex items-center gap-1 text-xs font-bold text-rose-500"><X size={13} /> Clear all filters</button>
        )}
      </Card>
      <p className="text-xs font-semibold text-slate-400 mb-3">{mine.length} {t('nav_transactions').toLowerCase()} {t('found')}</p>
      {mine.length === 0 ? <Card><Empty title={t('no_tx_match')} body={t('clear_filters')} /></Card> : (
        <div className="space-y-2.5">
          {mine.map(t => (
            <button key={t.id} onClick={() => setSel(t)} className="w-full text-left">
              <Card className="p-4 hover:border-violet-300 transition">
                <div className="flex items-start gap-3">
                  <div className="flex-1 min-w-0">
                    <p className="font-bold truncate">{t.title}</p>
                    <p className="text-xs text-slate-400 mt-1 flex items-center gap-1.5 flex-wrap">
                      <span>{fmtDateTime(t.createdAt)}</span>·<Badge tone="slate">{catLabel(t.category)}</Badge>
                    </p>
                    <p className="text-[11px] text-slate-400 font-mono mt-1 truncate">{t.id}</p>
                  </div>
                  <div className="text-right shrink-0"><p className="font-extrabold">{fmtMoney(t.amount)}</p><div className="mt-1"><Badge tone={statusTone(t.status)}>{t.status}</Badge></div></div>
                </div>
              </Card>
            </button>
          ))}
        </div>
      )}
      <Modal open={!!sel} onClose={() => setSel(null)} title="Transaction details">
        {sel && (
          <div className="space-y-4">
            <div className="rounded-2xl bg-slate-50 dark:bg-slate-800/70 p-4 space-y-2 text-sm">
              {[['Transaction ID', sel.id], ['Title', sel.title], ['Category', catLabel(sel.category)], ['Amount', fmtMoney(sel.amount)], ['Fee', fmtMoney(sel.fee)], ['Currency', sel.currency], ['Status', sel.status], ['Method', sel.method ?? '—'], ['Counterparty', sel.counterparty ?? '—'], ['Note', sel.note ?? '—'], ['Date', fmtDateTime(sel.createdAt)]].map(([k, v]) => (
                <div key={k} className="flex justify-between gap-4"><span className="text-slate-500 capitalize">{k}</span><span className="font-bold text-right capitalize">{v}</span></div>
              ))}
            </div>
            <Btn className="w-full" onClick={() => printReceipt(sel)}><FileText size={16} /> Download receipt (PDF)</Btn>
          </div>
        )}
      </Modal>
    </div>
  )
}

const NEWS_CATS = ['All', 'Bitcoin', 'Ethereum', 'Market Analysis', 'Blockchain', 'Trading']
export function NewsList() {
  const { db, t } = useApp()
  const [q, setQ] = useState(''); const [cat, setCat] = useState('All')
  const list = db.news.filter(n => (cat === 'All' || n.category === cat) && (n.title + n.excerpt).toLowerCase().includes(q.toLowerCase()))
  const featured = list.find(n => n.featured)
  return (
    <div>
      <PageHead title={t('news_title')} sub={t('news_sub')} />
      <div className="relative mb-3">
        <Search size={17} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
        <input value={q} onChange={e => setQ(e.target.value)} placeholder={t('search_news')} className="w-full rounded-2xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800/70 pl-10 pr-4 py-3 outline-none focus:ring-2 focus:ring-violet-500" />
      </div>
      <div className="flex gap-2 overflow-x-auto no-scrollbar mb-4">
        {NEWS_CATS.map(c => <button key={c} onClick={() => setCat(c)} className={`shrink-0 px-3.5 py-2 rounded-full text-xs font-bold ${cat === c ? 'bg-violet-600 text-white' : 'bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-slate-500'}`}>{c}</button>)}
      </div>
      {featured && (
        <Link to={'/news/' + featured.id}>
          <div className={`rounded-[28px] bg-gradient-to-br ${featured.gradient} text-white p-6 mb-4`}>
            <div className="flex items-center gap-3"><NewsLogo coin={featured.coin} category={featured.category} size={46} /><Badge tone="violet">Featured</Badge></div>
            <h2 className="text-2xl font-extrabold mt-3 leading-snug">{featured.title}</h2>
            <p className="text-white/85 text-sm mt-2">{featured.excerpt}</p>
            <p className="text-xs text-white/70 mt-3">{featured.source} · {fmtDate(featured.date)}</p>
          </div>
        </Link>
      )}
      {list.length === 0 ? <Card><Empty title="No news found" /></Card> : (
        <div className="space-y-3">
          {list.filter(n => n.id !== featured?.id).map(n => (
            <Link key={n.id} to={'/news/' + n.id}>
              <Card className="p-4 flex gap-4 mb-3">
                <NewsLogo coin={n.coin} category={n.category} size={56} />
                <div className="min-w-0"><Badge tone="cyan">{n.category}</Badge><p className="font-bold leading-snug mt-1">{n.title}</p><p className="text-xs text-slate-400 mt-1 line-clamp-2">{n.excerpt}</p><p className="text-[11px] text-slate-400 mt-1">{n.source} · {fmtDate(n.date)}</p></div>
              </Card>
            </Link>
          ))}
        </div>
      )}
    </div>
  )
}
