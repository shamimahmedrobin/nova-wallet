import { useMemo, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { Bell, Download, FileText, Search } from 'lucide-react'
import { useApp } from '../lib/store'
import { Badge, Btn, Card, Empty, Modal, statusTone } from '../components/ui'
import { downloadFile, fmtBDT, fmtDate, fmtDateTime } from '../lib/utils'
import { PageHead } from './Services'
import type { Tx } from '../lib/types'

const CATS = ['all', 'add_money', 'cash_out', 'send', 'receive', 'referral', 'loan_disbursement', 'loan_repayment', 'crypto_buy', 'crypto_sell', 'adjustment']
const catLabel = (c: string) => c.replace(/_/g, ' ')

export function Transactions() {
  const { user, db } = useApp()
  const [q, setQ] = useState(''); const [cat, setCat] = useState('all'); const [status, setStatus] = useState('all')
  const [from, setFrom] = useState(''); const [to, setTo] = useState(''); const [sel, setSel] = useState<Tx | null>(null)
  const mine = useMemo(() => db.txs.filter(t => t.userId === user?.id)
    .filter(t => cat === 'all' || t.category === cat)
    .filter(t => status === 'all' || t.status === status)
    .filter(t => !q || t.id.toLowerCase().includes(q.toLowerCase()) || t.title.toLowerCase().includes(q.toLowerCase()))
    .filter(t => !from || t.createdAt >= from)
    .filter(t => !to || t.createdAt <= to + 'T23:59'), [db.txs, user, q, cat, status, from, to])
  const exportCsv = () => {
    const csv = 'ID,Date,Category,Title,Amount,Fee,Currency,Status\n' + mine.map(t => [t.id, t.createdAt, t.category, '"' + t.title.replace(/"/g, '""') + '"', t.amount, t.fee, t.currency, t.status].join(',')).join('\n')
    downloadFile('novawallet-transactions.csv', csv, 'text/csv')
  }
  const printReceipt = (t: Tx) => {
    const w = window.open('', '_blank'); if (!w) return
    w.document.write(`<html><head><title>Receipt ${t.id}</title><style>body{font-family:sans-serif;padding:40px;color:#111}h1{color:#6d28d9}table{width:100%;border-collapse:collapse}td{padding:8px;border-bottom:1px solid #eee}</style></head><body><h1>NovaWallet — Transaction Receipt</h1><table>
      <tr><td>Transaction ID</td><td><b>${t.id}</b></td></tr><tr><td>Title</td><td>${t.title}</td></tr>
      <tr><td>Category</td><td>${catLabel(t.category)}</td></tr><tr><td>Amount</td><td><b>৳${t.amount.toLocaleString()}</b></td></tr>
      <tr><td>Fee</td><td>৳${t.fee}</td></tr><tr><td>Status</td><td>${t.status}</td></tr>
      <tr><td>Date</td><td>${new Date(t.createdAt).toLocaleString()}</td></tr>${t.note ? `<tr><td>Note</td><td>${t.note}</td></tr>` : ''}</table>
      <p style="color:#888;font-size:12px;margin-top:24px">This receipt was generated by NovaWallet. Save as PDF from the print dialog.</p><script>window.print()</script></body></html>`)
    w.document.close()
  }
  return (
    <div>
      <PageHead title="Transactions" sub="Full history with filters, receipts and CSV export." />
      <div className="relative mb-3">
        <Search size={17} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
        <input value={q} onChange={e => setQ(e.target.value)} placeholder="Search by transaction ID or title…" className="w-full rounded-2xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800/70 pl-10 pr-4 py-3 text-[15px] outline-none focus:ring-2 focus:ring-violet-500" />
      </div>
      <div className="flex gap-2 overflow-x-auto no-scrollbar mb-3">
        {CATS.map(c => <button key={c} onClick={() => setCat(c)} className={`shrink-0 px-3.5 py-2 rounded-full text-xs font-bold capitalize ${cat === c ? 'bg-violet-600 text-white' : 'bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-slate-500'}`}>{catLabel(c)}</button>)}
      </div>
      <div className="grid grid-cols-3 gap-2 mb-4">
        <select value={status} onChange={e => setStatus(e.target.value)} className="rounded-xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 px-3 py-2.5 text-sm"><option value="all">All status</option>{['pending', 'processing', 'completed', 'approved', 'rejected'].map(s => <option key={s}>{s}</option>)}</select>
        <input type="date" value={from} onChange={e => setFrom(e.target.value)} className="rounded-xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 px-3 py-2.5 text-sm" />
        <input type="date" value={to} onChange={e => setTo(e.target.value)} className="rounded-xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 px-3 py-2.5 text-sm" />
      </div>
      <Btn variant="ghost" className="mb-4" onClick={exportCsv}><Download size={16} /> Export CSV ({mine.length})</Btn>
      {mine.length === 0 ? <Card><Empty title="No transactions match" body="Try clearing the filters." /></Card> : (
        <div className="space-y-2">
          {mine.map(t => (
            <button key={t.id} onClick={() => setSel(t)} className="w-full text-left">
              <Card className="p-4 flex items-center gap-3 hover:border-violet-300 transition">
                <div className="flex-1 min-w-0"><p className="font-bold truncate">{t.title}</p><p className="text-xs text-slate-400">{t.id} · {fmtDateTime(t.createdAt)} · <span className="capitalize">{catLabel(t.category)}</span></p></div>
                <div className="text-right"><p className="font-extrabold">{fmtBDT(t.amount)}</p><Badge tone={statusTone(t.status)}>{t.status}</Badge></div>
              </Card>
            </button>
          ))}
        </div>
      )}
      <Modal open={!!sel} onClose={() => setSel(null)} title="Transaction details">
        {sel && (
          <div className="space-y-4">
            <div className="rounded-2xl bg-slate-50 dark:bg-slate-800/70 p-4 space-y-2 text-sm">
              {[['Transaction ID', sel.id], ['Title', sel.title], ['Category', catLabel(sel.category)], ['Amount', fmtBDT(sel.amount)], ['Fee', fmtBDT(sel.fee, 2)], ['Currency', sel.currency], ['Status', sel.status], ['Method', sel.method ?? '—'], ['Counterparty', sel.counterparty ?? '—'], ['Note', sel.note ?? '—'], ['Date', fmtDateTime(sel.createdAt)]].map(([k, v]) => (
                <div key={k} className="flex justify-between gap-4"><span className="text-slate-500 capitalize">{k}</span><span className="font-bold text-right capitalize">{v}</span></div>
              ))}
            </div>
            <Btn className="w-full" onClick={() => printReceipt(sel)}><FileText size={16} /> Download receipt (PDF)</Btn>
          </div>
        )}
      </Modal>
    </div>
  )
}

const NEWS_CATS = ['All', 'Bitcoin', 'Ethereum', 'Market Analysis', 'Blockchain', 'Trading']
export function NewsList() {
  const { db } = useApp()
  const [q, setQ] = useState(''); const [cat, setCat] = useState('All')
  const list = db.news.filter(n => (cat === 'All' || n.category === cat) && (n.title + n.excerpt).toLowerCase().includes(q.toLowerCase()))
  const featured = list.find(n => n.featured)
  return (
    <div>
      <PageHead title="Crypto News" sub="Latest updates, analysis and education from the Nova desk." />
      <div className="relative mb-3">
        <Search size={17} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
        <input value={q} onChange={e => setQ(e.target.value)} placeholder="Search news…" className="w-full rounded-2xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800/70 pl-10 pr-4 py-3 outline-none focus:ring-2 focus:ring-violet-500" />
      </div>
      <div className="flex gap-2 overflow-x-auto no-scrollbar mb-4">
        {NEWS_CATS.map(c => <button key={c} onClick={() => setCat(c)} className={`shrink-0 px-3.5 py-2 rounded-full text-xs font-bold ${cat === c ? 'bg-violet-600 text-white' : 'bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-slate-500'}`}>{c}</button>)}
      </div>
      {featured && (
        <Link to={'/app/news/' + featured.id}>
          <div className={`rounded-[28px] bg-gradient-to-br ${featured.gradient} text-white p-6 mb-4`}>
            <Badge tone="violet">Featured</Badge>
            <h2 className="text-2xl font-extrabold mt-3 leading-snug">{featured.title}</h2>
            <p className="text-white/85 text-sm mt-2">{featured.excerpt}</p>
            <p className="text-xs text-white/70 mt-3">{featured.source} · {fmtDate(featured.date)}</p>
          </div>
        </Link>
      )}
      {list.length === 0 ? <Card><Empty title="No news found" /></Card> : (
        <div className="space-y-3">
          {list.filter(n => n.id !== featured?.id).map(n => (
            <Link key={n.id} to={'/app/news/' + n.id}>
              <Card className="p-4 flex gap-4 mb-3">
                <div className={`w-16 h-16 shrink-0 rounded-2xl bg-gradient-to-br ${n.gradient} flex items-center justify-center text-white text-2xl font-extrabold`}>{n.title[0]}</div>
                <div className="min-w-0"><Badge tone="cyan">{n.category}</Badge><p className="font-bold leading-snug mt-1">{n.title}</p><p className="text-xs text-slate-400 mt-1 line-clamp-2">{n.excerpt}</p><p className="text-[11px] text-slate-400 mt-1">{n.source} · {fmtDate(n.date)}</p></div>
              </Card>
            </Link>
          ))}
        </div>
      )}
    </div>
  )
}
export function NewsDetail() {
  const { id } = useParams(); const { db } = useApp()
  const n = db.news.find(x => x.id === id)
  if (!n) return <Card><Empty title="News not found" /></Card>
  return (
    <article className="anim-fade-up">
      <div className={`rounded-[28px] bg-gradient-to-br ${n.gradient} text-white p-6 mb-5`}>
        <Badge tone="violet">{n.category}</Badge>
        <h1 className="text-2xl sm:text-3xl font-extrabold mt-3 leading-snug">{n.title}</h1>
        <p className="text-sm text-white/80 mt-3">✍️ {n.source} · 📅 {fmtDate(n.date)}</p>
      </div>
      <Card className="p-6">
        <p className="font-semibold text-slate-700 dark:text-slate-200 leading-relaxed">{n.excerpt}</p>
        {n.body.split('\n\n').map((p, i) => <p key={i} className="mt-4 text-slate-600 dark:text-slate-300 leading-relaxed">{p}</p>)}
        <p className="mt-6 text-xs text-slate-400 border-t border-slate-100 dark:border-slate-800 pt-4">Source attribution: {n.source}. Market information is educational, not financial advice.</p>
      </Card>
    </article>
  )
}
export function Notifications() {
  const { user, db, markAllRead, markRead } = useApp()
  const mine = db.notifications.filter(n => n.userId === user?.id)
  return (
    <div>
      <div className="flex items-start justify-between"><PageHead title="Notifications" sub="Deposits, transfers, loans, security & market alerts." />
        <Btn variant="ghost" onClick={markAllRead}>Mark all read</Btn></div>
      {mine.length === 0 ? <Card><Empty title="No notifications" body="You're all caught up." /></Card> : (
        <div className="space-y-2">
          {mine.map(n => (
            <button key={n.id} onClick={() => markRead(n.id)} className="w-full text-left">
              <Card className={`p-4 flex gap-3 ${!n.read ? 'border-l-4 !border-l-violet-500' : 'opacity-75'}`}>
                <div className="p-2.5 rounded-2xl bg-violet-100 dark:bg-violet-500/15 text-violet-600 h-fit"><Bell size={17} /></div>
                <div className="flex-1"><p className="font-bold text-sm">{n.title} {!n.read && <span className="ml-1 inline-block w-2 h-2 rounded-full bg-rose-500" />}</p><p className="text-sm text-slate-500">{n.body}</p><p className="text-[11px] text-slate-400 mt-1 capitalize">{n.kind} · {fmtDateTime(n.createdAt)}</p></div>
              </Card>
            </button>
          ))}
        </div>
      )}
    </div>
  )
}
